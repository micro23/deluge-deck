import { writeFile } from 'node:fs/promises';
import { SPORTS_CLUBS } from '../src/app/sports-clubs.js';

// Established palettes remain hand-tuned in sports.css. New palettes share
// geometry, with materials and pigments owned by each team's metadata.
const mix = (first, second, amount) => `#${[1,3,5].map(index => Math.round(parseInt(first.slice(index,index+2),16)*(1-amount)+parseInt(second.slice(index,index+2),16)*amount).toString(16).padStart(2,'0')).join('')}`;
let css = '/* Generated by scripts/generate-sports-palettes.mjs. Team colors and\n   materials come from src/app/sports-clubs.js; no non-sports selectors. */\n';
for (const [id, club] of Object.entries(SPORTS_CLUBS)) {
  if (!club.material || club.material === 'bespoke') continue;
  const light = ['porcelain','ice'].includes(club.material);
  const top = light ? '#ffffff' : mix('#080e18',club.primary,.32);
  const bottom = light ? (club.material === 'ice' ? '#e4eef8' : '#edf2f9') : mix('#070d16',club.primary,.14);
  const ink = light ? mix('#0a1628',club.primary,.15) : '#ffffff';
  const muted = light ? '#23364d' : '#d3deed';
  const pattern = club.sport === 'Baseball' ? `repeating-linear-gradient(90deg,${club.primary}14 0 1px,transparent 1px 13px)`
    : club.sport === 'Football' ? `repeating-linear-gradient(90deg,transparent 0 31px,${club.accent}0a 31px 32px)`
    : club.sport === 'Hockey' ? `repeating-linear-gradient(135deg,${club.primary}06 0 1px,transparent 1px 17px)`
    : `repeating-linear-gradient(0deg,${club.secondary}08 0 1px,transparent 1px 9px)`;
  css += `:root[data-theme="${id}"] {
  color-scheme:dark;
  --bg:${mix('#040810',club.primary,.06)}; --surface:${mix('#0a111c',club.primary,.10)}; --surface-2:${mix('#0d1725',club.primary,.13)}; --surface-3:${mix('#132032',club.primary,.16)};
  --text:#ffffff; --muted:#d9e0ea; --muted-2:#c7d2e1;
  --cyan:${club.accent}; --accent-fg:#070b12; --violet:#d6d9ff; --amber:#ffe0a0; --green:#b2edc9; --danger:#ffc2c9;
  --line:#52647c; --line-strong:#8e9fb7;
  --club-primary:${club.primary}; --club-secondary:${club.secondary}; --club-edge:${club.accent};
  --club-art:url('../assets/sports/${id}-stadium.webp');
  --club-pattern:${pattern};
  --club-card:linear-gradient(145deg,${top},${bottom});
  --club-card-ink:${ink}; --club-card-muted:${muted};
  --club-card-icon:${light ? '#f8fbff' : mix('#060b14',club.primary,.13)}; --club-card-line:${light ? '#75879e' : '#8e9fb7'};
  --theme-radius:${club.sport === 'Football' ? '8' : club.sport === 'Hockey' ? '11' : '12'}px; --theme-control-radius:7px;
}
:root[data-theme="${id}"] body .stats-grid .stat-card:nth-child(even) { border-top-color:var(--club-secondary)!important; }
:root[data-theme="${id}"] body .stats-grid .stat-card > .stat-spark polyline { stroke:${light ? '#324c70' : club.accent}; }
:root[data-theme="${id}"] body .stats-grid .stat-card > .stat-spark polygon { fill:${light ? '#324c7020' : `${club.accent}26`}; }
:root[data-theme="${id}"] body .progress-bar { background:linear-gradient(90deg,${mix(club.accent,'#ffffff',.18)},${club.accent})!important; }
@media (max-width:659px) {
  :root[data-theme="${id}"] body .workspace .stats-grid .stat-card:nth-child(n+3) { height:44px!important; min-height:44px!important; justify-content:center!important; }
  :root[data-theme="${id}"] body .workspace .stats-grid .stat-card:nth-child(n+3) > div:nth-child(2) { flex-direction:column!important; flex-wrap:nowrap; gap:0!important; }
  :root[data-theme="${id}"] body .stats-grid .stat-card:nth-child(n+3) > .theme-detail { top:12px; }
}
`;
}
await writeFile(new URL('../src/themes/sports-expansion.css',import.meta.url),css);
console.log('Generated isolated palettes for the 20 new sports themes');
